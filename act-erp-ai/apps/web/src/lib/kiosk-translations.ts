const normalize = (text: string) => text.replace(/\s+/g, " ").trim();

/** Translate known kiosk copy; unknown text stays visible in English. */
export function translateKiosk(text: string, language: "en" | "es"): string {
  if (language === "en") return text;
  const key = normalize(text);
  const direct = kioskSpanish[key];
  if (direct) return direct;

  const rateLimit = key.match(
    /^Too many incorrect PIN attempts\. Try again in about (\d+) minutes?\.$/,
  );
  if (rateLimit) {
    const count = Number(rateLimit[1]);
    return `Demasiados intentos de PIN incorrectos. Inténtalo de nuevo en aproximadamente ${count} ${count === 1 ? "minuto" : "minutos"}.`;
  }
  const networkDenied = key.match(
    /^This kiosk can only be used from the approved facility network \(your connection appears as (.+)\)\.$/,
  );
  if (networkDenied)
    return `Este quiosco solo se puede usar desde la red aprobada de las instalaciones (tu conexión aparece como ${networkDenied[1]}).`;
  const staleShift = key.match(
    /^Your shift has been open more than (\d+) hours\. Clock out to close it, then clock in again\.$/,
  );
  if (staleShift)
    return `Tu turno ha estado abierto por más de ${staleShift[1]} horas. Registra la salida para cerrarlo y luego registra la entrada de nuevo.`;
  return text;
}
