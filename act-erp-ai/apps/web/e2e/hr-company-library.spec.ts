import { test, expect } from "@playwright/test";
import { db } from "./support/db";
import { ADMIN_STATE } from "./support/test-data";
import { fakePdf, sessionFor, PT } from "./support/payroll-time";

test.use({storageState: ADMIN_STATE});

test("private compliance upload, duplicate detection, immutable versions, filters, and timeclock preservation", async ({page, browser}) => {
  const before = await Promise.all([db.timeEntry.findMany({orderBy: {id: "asc"}}), db.timeBreak.findMany({orderBy: {id: "asc"}}), db.contractTimeEntry.findMany({orderBy: {id: "asc"}}), db.contractTimeBreak.findMany({orderBy: {id: "asc"}}), db.kioskSession.findMany({orderBy: {id: "asc"}})]);
  const tag = `HR Q3 ${Date.now()}`;
  await page.goto("/admin/documents");
  await page.getByRole("link", {name: "Company library", exact: true}).click();
  await page.getByRole("button", {name: "Upload company document", exact: true}).click();
  await page.getByLabel("Title", {exact: true}).fill(tag);
  await page.getByLabel("Category", {exact: true}).first().selectOption("PAYROLL_COMPLIANCE");
  const bytes = fakePdf(tag);
  await page.getByLabel("File", {exact: true}).setInputFiles({name: "q3-return.pdf", mimeType: "application/pdf", buffer: bytes});
  await page.getByLabel("Tax or plan year").fill("2026");
  await page.getByLabel("Quarter", {exact: true}).first().selectOption("3");
  await page.getByRole("button", {name: "Save draft"}).click();
  const row = page.locator("section").filter({has: page.getByRole("heading", {name: tag, exact: true})});
  await expect(row).toBeVisible();
  await expect.poll(async () => db.companyDocumentVersion.count({where: {document: {title: tag}}})).toBe(1);
  const version = await db.companyDocumentVersion.findFirstOrThrow({where: {document: {title: tag}}});
  expect(version.status).toBe("DRAFT"); expect(version.year).toBe(2026); expect(version.quarter).toBe(3);
  await row.locator("summary").click();
  await row.getByRole("button", {name: /^Review /}).click();
  await expect(page.getByLabel("Approved use").locator("option")).toHaveCount(1);
  await page.getByLabel("Review note").fill("Verified company-only payroll record.");
  await page.getByRole("button", {name: "Approve version", exact: true}).click();
  await expect(row.getByText("Approved", {exact: true})).toBeVisible();
  const context = await sessionFor(browser, "hr-library-employee", PT.rex.email);
  const denied = await context.request.get(`/api/company-documents/${version.id}/file`);
  expect(denied.status()).toBe(404);
  const deniedPage = await context.newPage(); await deniedPage.goto("/admin/documents/company");
  await expect(deniedPage).not.toHaveURL(/\/admin\/documents\/company$/);
  await context.close();
  await row.getByRole("button", {name: "New version"}).click();
  await page.getByLabel("File", {exact: true}).setInputFiles({name: "renamed.pdf", mimeType: "application/pdf", buffer: bytes});
  await page.getByRole("button", {name: "Save draft"}).click();
  await expect(page.getByText(/This exact file is already/)).toBeVisible();
  expect(await db.companyDocumentVersion.count({where: {documentId: version.documentId}})).toBe(1);
  await page.getByLabel("File", {exact: true}).setInputFiles({name: "q3-return-v2.pdf", mimeType: "application/pdf", buffer: fakePdf(`${tag}-v2`)});
  await page.getByRole("button", {name: "Save draft"}).click();
  await expect.poll(async () => db.companyDocumentVersion.count({where: {documentId: version.documentId}})).toBe(2);
  expect((await db.companyDocumentVersion.findUniqueOrThrow({where: {id: version.id}})).sha256).toBe(version.sha256);
  await row.getByRole("button", {name: "Archive", exact: true}).click();
  await row.getByRole("textbox", {name: "Reason for archive change"}).fill("Retain for historical HR records");
  await row.getByRole("button", {name: "Confirm archive"}).click();
  await expect.poll(async () => (await db.companyDocument.findUniqueOrThrow({where: {id: version.documentId}})).isArchived).toBe(true);
  const after = await Promise.all([db.timeEntry.findMany({orderBy: {id: "asc"}}), db.timeBreak.findMany({orderBy: {id: "asc"}}), db.contractTimeEntry.findMany({orderBy: {id: "asc"}}), db.contractTimeBreak.findMany({orderBy: {id: "asc"}}), db.kioskSession.findMany({orderBy: {id: "asc"}})]);
  expect(after).toEqual(before);
});
